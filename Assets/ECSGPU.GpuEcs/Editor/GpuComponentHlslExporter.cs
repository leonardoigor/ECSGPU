using System;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using UnityEditor;
using UnityEditor.Callbacks;
using UnityEngine;

namespace ECSGPU.GpuEcs.Editor
{
    public static class GpuComponentHlslExporter
    {
        public const string OutputAssetPath = "Assets/ECSGPU.GpuEcs/Generated/GpuComponents.auto.hlsl";
        static bool _exportQueued;

        [MenuItem("Tools/GPU ECS/Export GPU Components to HLSL")]
        public static void ExportFromMenu()
        {
            ExportNow(logResult: true);
        }

        [InitializeOnLoadMethod]
        static void Initialize()
        {
            QueueExport();
        }

        [DidReloadScripts]
        static void OnScriptsReloaded()
        {
            QueueExport();
        }

        public static void QueueExport()
        {
            if (_exportQueued)
                return;

            _exportQueued = true;
            EditorApplication.delayCall += ExportWhenReady;
        }

        public static string BuildHlsl()
        {
            var types = TypeCache.GetTypesWithAttribute<GpuComponentAttribute>()
                .Where(t => t.IsValueType && !t.IsAbstract)
                .OrderBy(t => t.FullName, StringComparer.Ordinal)
                .ToArray();

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("// Generated from [GpuComponent] structs.");
            sb.AppendLine("// Do not edit manually.");
            sb.AppendLine("#ifndef ECSGPU_GPU_COMPONENTS_AUTO_INCLUDED");
            sb.AppendLine("#define ECSGPU_GPU_COMPONENTS_AUTO_INCLUDED");
            sb.AppendLine();

            foreach (var type in types)
            {
                var attr = type.GetCustomAttribute<GpuComponentAttribute>();
                string hlslName = string.IsNullOrWhiteSpace(attr?.HlslName) ? type.Name : attr.HlslName;
                sb.Append(GpuTypeMapper.GenerateHlslStruct(type, hlslName));
                sb.AppendLine();
            }

            sb.AppendLine("#endif");
            return sb.ToString();
        }

        public static void ExportNow(bool logResult)
        {
            string hlsl = BuildHlsl();
            string fullPath = GetOutputFullPath();
            string directory = Path.GetDirectoryName(fullPath);

            if (!Directory.Exists(directory))
                Directory.CreateDirectory(directory);

            string previous = File.Exists(fullPath) ? File.ReadAllText(fullPath) : null;
            if (string.Equals(previous, hlsl, StringComparison.Ordinal))
            {
                if (logResult)
                    Debug.Log($"[GPU ECS] HLSL export is already up to date: {OutputAssetPath}");
                return;
            }

            File.WriteAllText(fullPath, hlsl, new UTF8Encoding(false));
            AssetDatabase.ImportAsset(OutputAssetPath, ImportAssetOptions.ForceUpdate);

            if (logResult)
                Debug.Log($"[GPU ECS] Exported [GpuComponent] structs to HLSL: {OutputAssetPath}");
        }

        static void ExportWhenReady()
        {
            if (EditorApplication.isCompiling || EditorApplication.isUpdating)
            {
                EditorApplication.delayCall += ExportWhenReady;
                return;
            }

            _exportQueued = false;
            ExportNow(logResult: false);
        }

        static string GetOutputFullPath()
        {
            return Path.Combine(Directory.GetCurrentDirectory(), OutputAssetPath.Replace('/', Path.DirectorySeparatorChar));
        }
    }
}
