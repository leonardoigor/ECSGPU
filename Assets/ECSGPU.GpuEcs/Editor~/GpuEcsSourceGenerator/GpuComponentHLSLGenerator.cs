using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace ECSGPU.GpuEcs.SourceGenerator
{
    [Generator]
    public class GpuComponentHLSLGenerator : IIncrementalGenerator
    {
        const string GpuComponentAttributeFullName = "ECSGPU.GpuEcs.GpuComponentAttribute";

        static readonly System.Collections.Generic.Dictionary<string, (string HlslType, int Stride)> TypeMap =
            new System.Collections.Generic.Dictionary<string, (string, int)>
            {
                { "System.Single",   ("float",  4)  },
                { "System.Int32",    ("int",    4)  },
                { "System.UInt32",   ("uint",   4)  },
                { "System.Boolean",  ("uint",   4)  },
                { "UnityEngine.Vector2", ("float2", 8) },
                { "UnityEngine.Vector3", ("float3", 12) },
                { "UnityEngine.Vector4", ("float4", 16) },
                { "UnityEngine.Color",   ("float4", 16) },
                { "UnityEngine.Matrix4x4", ("float4x4", 64) },
                { "UnityEngine.Quaternion", ("float4", 16) },
                { "Unity.Mathematics.float2", ("float2", 8) },
                { "Unity.Mathematics.float3", ("float3", 12) },
                { "Unity.Mathematics.float4", ("float4", 16) },
                { "Unity.Mathematics.int2",   ("int2", 8) },
                { "Unity.Mathematics.int3",   ("int3", 12) },
                { "Unity.Mathematics.int4",   ("int4", 16) },
                { "Unity.Mathematics.uint2",  ("uint2", 8) },
                { "Unity.Mathematics.uint3",  ("uint3", 12) },
                { "Unity.Mathematics.uint4",  ("uint4", 16) },
                { "Unity.Mathematics.quaternion", ("float4", 16) },
            };

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var structProvider = context.SyntaxProvider
                .ForAttributeWithMetadataName(
                    GpuComponentAttributeFullName,
                    predicate: (node, _) => node is StructDeclarationSyntax,
                    transform: (ctx, _) => GetStructInfo(ctx))
                .Where(static m => m != null);

            var allStructs = structProvider.Collect();

            context.RegisterSourceOutput(allStructs, (spc, structs) =>
            {
                if (structs.Length == 0) return;
                GenerateHLSLDefinitions(spc, structs);
            });
        }

        static StructInfo GetStructInfo(GeneratorAttributeSyntaxContext ctx)
        {
            if (!(ctx.TargetSymbol is INamedTypeSymbol structSymbol))
                return null;

            string name = structSymbol.Name;
            string ns = structSymbol.ContainingNamespace?.IsGlobalNamespace == true
                ? null
                : structSymbol.ContainingNamespace?.ToDisplayString();

            var attribute = structSymbol.GetAttributes()
                .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == GpuComponentAttributeFullName);

            string hlslName = null;
            if (attribute != null)
            {
                foreach (var named in attribute.NamedArguments)
                {
                    if (named.Key == "HlslName" && named.Value.Value is string val)
                        hlslName = val;
                }
            }

            var fields = structSymbol.GetMembers()
                .OfType<IFieldSymbol>()
                .Where(f => !f.IsStatic && !f.IsConst)
                .Select(f =>
                {
                    string csType = f.Type.ToDisplayString();
                    string hlslType = "float";
                    int stride = 4;

                    if (TypeMap.TryGetValue(csType, out var mapping))
                    {
                        hlslType = mapping.HlslType;
                        stride = mapping.Stride;
                    }

                    return new FieldInfo(f.Name, hlslType, stride, csType);
                })
                .ToArray();

            return new StructInfo(name, ns, hlslName ?? name, fields);
        }

        static void GenerateHLSLDefinitions(SourceProductionContext context, ImmutableArray<StructInfo> structs)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("// Generated by ECSGPU.GpuEcs Source Generator");
            sb.AppendLine("#pragma once");
            sb.AppendLine();

            var csharpSb = new StringBuilder();
            csharpSb.AppendLine("// <auto-generated/>");
            csharpSb.AppendLine("// Generated by ECSGPU.GpuEcs Source Generator");
            csharpSb.AppendLine("using System;");
            csharpSb.AppendLine();
            csharpSb.AppendLine("namespace ECSGPU.GpuEcs.Generated");
            csharpSb.AppendLine("{");

            foreach (var structInfo in structs)
            {
                sb.AppendLine($"struct {structInfo.HlslName}");
                sb.AppendLine("{");
                foreach (var field in structInfo.Fields)
                {
                    sb.AppendLine($"    {field.HlslType} {field.Name};");
                }
                sb.AppendLine("};");
                sb.AppendLine();

                string safeName = structInfo.Name;
                csharpSb.AppendLine($"    internal static class {safeName}_HLSL");
                csharpSb.AppendLine("    {");
                csharpSb.AppendLine($"        public const string HLSL = @\"");
                csharpSb.AppendLine($"struct {structInfo.HlslName}");
                csharpSb.AppendLine("{");
                foreach (var field in structInfo.Fields)
                {
                    csharpSb.AppendLine($"    {field.HlslType} {field.Name};");
                }
                csharpSb.AppendLine("};\";");
                csharpSb.AppendLine();

                int totalStride = structInfo.Fields.Sum(f => f.Stride);
                csharpSb.AppendLine($"        public const int Stride = {totalStride};");
                csharpSb.AppendLine($"        public const int FieldCount = {structInfo.Fields.Length};");
                csharpSb.AppendLine("    }");
                csharpSb.AppendLine();
            }

            csharpSb.AppendLine("}");

            context.AddSource("GpuHLSLDefinitions.g.cs", SourceText.From(csharpSb.ToString(), Encoding.UTF8));
        }

        class StructInfo
        {
            public readonly string Name;
            public readonly string Namespace;
            public readonly string HlslName;
            public readonly FieldInfo[] Fields;

            public StructInfo(string name, string ns, string hlslName, FieldInfo[] fields)
            {
                Name = name;
                Namespace = ns;
                HlslName = hlslName;
                Fields = fields;
            }
        }

        class FieldInfo
        {
            public readonly string Name;
            public readonly string HlslType;
            public readonly int Stride;
            public readonly string CsType;

            public FieldInfo(string name, string hlslType, int stride, string csType)
            {
                Name = name;
                HlslType = hlslType;
                Stride = stride;
                CsType = csType;
            }
        }
    }
}
